import 'dart:io';

import 'package:path_provider/path_provider.dart';

/// Где приложение работает и что из этого следует.
///
/// Заведено отдельным файлом, а не проверками `Platform.isAndroid` по месту:
/// таких мест в `main.dart` под сотню, и разбросанные по коду проверки
/// платформы — верный способ однажды пропустить одну и получить падение
/// ровно там, где проверить некому.
///
/// Правило простое: всё, что РЕШАЕТ, доступна ли возможность, живёт здесь;
/// всё, что ей пользуется, спрашивает отсюда.
class Env {
  Env._();

  /// Настольная система: есть окно, трей, системный прокси, дочерние процессы.
  static bool get isDesktop =>
      Platform.isWindows || Platform.isLinux || Platform.isMacOS;

  static bool get isAndroid => Platform.isAndroid;

  /// Ядро запускается ОТДЕЛЬНЫМ ПРОЦЕССОМ.
  ///
  /// Windows: `sing-box.exe` и `xray.exe` — обычные дочерние процессы, ими
  /// управляют через `Process`, конфиги передают файлами.
  ///
  /// Android: так нельзя. Интерфейс туннеля выдаёт система в виде файлового
  /// дескриптора, и передать его чужому процессу невозможно, а запуск
  /// сторонних исполняемых файлов там запрещён. Ядро вкомпилировано в
  /// приложение библиотекой, и им управляет `VpnService`.
  static bool get coreRunsAsProcess => isDesktop;

  /// Есть окно, которое можно двигать, прятать и закрывать крестиком, и трей,
  /// куда его прятать. На Android «свернуть в трей» смысла не имеет —
  /// приложение живёт службой переднего плана с уведомлением.
  static bool get hasWindowAndTray => isDesktop;

  /// Системный прокси нужно подменять.
  ///
  /// На Android — нет, и это не упрощение, а устройство системы: весь трафик
  /// и так идёт через интерфейс туннеля, перехватывать нечего. Вся ветка
  /// WinINET из настольной версии там просто не применяется.
  static bool get needsSystemProxy => Platform.isWindows;

  /// Ядра обновляются отдельно от приложения.
  ///
  /// На Windows это два .exe рядом с приложением, их можно подменить на ходу.
  /// На Android ядро вкомпилировано в APK и обновляется только вместе с
  /// приложением — предлагать «проверить обновления ядер» там значит обещать
  /// то, чего не будет.
  static bool get coresUpdateSeparately => isDesktop;

  /// Правила для программ задаются путём к исполняемому файлу (Windows) или
  /// именем пакета (Android). Разные ключи — разные экраны выбора.
  static bool get appRulesUsePaths => isDesktop;

  /// Тест задержки умеет поднимать ОТДЕЛЬНЫЕ пробные ядра.
  ///
  /// На Windows он запускает служебные процессы на портах 17390+ и меряет
  /// сквозной путь, не трогая рабочее соединение. На Android процессов нет:
  /// там доступен либо замер TCP-подключения до сервера (не требует ядра
  /// вообще), либо опрос уже работающего ядра через Clash API.
  static bool get canSpawnProbeCores => isDesktop;

  /// Готовый путь к рабочему каталогу, когда его нельзя вычислить синхронно.
  ///
  /// Заполняется в `main()` на Android и дальше не меняется. Живёт здесь, а не
  /// в `main.dart`, потому что нужен и экрану диагностики: тот показывает
  /// конфиги ядра и должен знать, где их искать. На Windows остаётся `null` —
  /// там путь считается от расположения самой программы.
  static String? workDirOverride;

  static String? _workDirCache;

  /// Каталог рабочих файлов: конфиги ядра, лог, наборы правил.
  ///
  /// На Windows логика прежняя и вынесена в вызывающий код (рядом с .exe,
  /// а если туда нельзя писать — в профиль). Здесь — только android-ветка:
  /// система выдаёт приложению собственный каталог, и другого пути нет.
  static Future<String> androidWorkDir() async {
    final cached = _workDirCache;
    if (cached != null) return cached;
    final dir = await getApplicationSupportDirectory();
    _workDirCache = dir.path;
    return dir.path;
  }
}
